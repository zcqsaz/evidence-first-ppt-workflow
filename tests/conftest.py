def make_metadata(path: Path, filename: str, digest: str, *, valid: bool = True) -> None:
    fields = [
        "asset_id", "filename", "case_name", "ppt_page", "figure_title", "source_type",
        "source_organization", "source_title", "publication_year", "figure_number", "page_number",
        "doi", "source_url", "download_url", "license_or_usage_note", "verification_status", "file_sha256"
    ]
    row = {
        "asset_id": "asset-001",
        "filename": filename,
        "case_name": "QA test",
        "ppt_page": "2",
        "figure_title": "自有无版权测试图",
        "source_type": "project-owned",
        "source_organization": "Evidence-First PPT Workflow",
        "source_title": "Automated test asset",
        "publication_year": "2026",
        "figure_number": "1",
        "page_number": "",
        "doi": "",
        "source_url": "https://example.com/evidence",
        "download_url": "https://example.com/evidence.png",
        "license_or_usage_note": "Generated by the test suite and safe to redistribute.",
        "verification_status": "verified" if valid else "unverified",
        "file_sha256": digest,
    }
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerow(row)


