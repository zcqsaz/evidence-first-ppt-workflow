def _set_font(text_frame, name: str = "Microsoft YaHei") -> None:
    for paragraph in text_frame.paragraphs:
        for run in paragraph.runs:
            run.font.name = name
            run.font.size = Pt(18)


def _add_text(slide, text: str, left: float, top: float, width: float, height: float) -> None:
    shape = slide.shapes.add_textbox(Inches(left), Inches(top), Inches(width), Inches(height))
    shape.text_frame.text = text
    _set_font(shape.text_frame)


def make_deck(path: Path, image_path: Path, *, bad: bool = False) -> None:
    presentation = Presentation()
    presentation.slide_width = Inches(13.333333)
    presentation.slide_height = Inches(7.5)
    blank = presentation.slide_layouts[6]
    cover = presentation.slides.add_slide(blank)
    _add_text(cover, "Evidence-First PPT 测试文件", 1.0, 2.8, 11.0, 0.7)

    for slide_number in range(2, 4 if bad else 3):
        slide = presentation.slides.add_slide(blank)
        phrase = "阅读要点：" if bad and slide_number == 2 else "核心结论："
        body = (
            f"{phrase}真实科研素材必须先核验项目归属、变量、时间、区域和单位。\n"
            "第一，使用官方机构或同行评议论文原图；第二，保持坐标轴与图例完整；\n"
            "第三，图片等比显示且裁剪值为零；第四，每页保留可追溯的页脚来源。"
        )
        _add_text(slide, "科研素材完整性与证据链", 0.8, 0.5, 11.7, 0.6)
        _add_text(slide, body, 0.8, 1.4, 6.0, 3.5)
        picture = slide.shapes.add_picture(str(image_path), Inches(7.2), Inches(1.5), width=Inches(5.0))
        if bad and slide_number == 2:
            picture.crop_right = 0.1
        _add_text(slide, "图源：测试项目自有无版权图，2026。", 7.2, 5.35, 5.0, 0.35)
        _add_text(slide, f"{slide_number:02d}", 6.4666665, 7.05, 0.4, 0.25)
    presentation.save(path)


